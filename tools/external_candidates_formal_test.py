def main(report_path: Path = DEFAULT_REPORT_PATH) -> dict:
    client = MarketDataClient()
    now = datetime.now(timezone.utc)
    history_cache: dict[tuple[str, str], pd.DataFrame] = {}
    runs: dict[str, dict] = {}

    print(f"=== external_candidates_formal_test: {len(EXTERNAL_CANDIDATES)} pre-registered candidates, now={now.isoformat()} ===", flush=True)

    def _write_report() -> dict:
        report = {"generated_at": now.isoformat(), "runs": runs}
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(json.dumps(report, indent=2, default=str))
        return report

    for idx, candidate in enumerate(EXTERNAL_CANDIDATES, start=1):
        name = candidate["name"]
        assert name not in NATIVE_NAME_COLLISIONS_TO_AVOID, f"{name} collides with a native graveyard name"

        if candidate["untestable_reason"] is not None:
            print(f"[{idx}/{len(EXTERNAL_CANDIDATES)}] {name}: UNTESTABLE -- {candidate['untestable_reason'][:100]}...", flush=True)
            runs[name] = {"name": name, "verdict": auto_tester.VERDICT_UNTESTABLE, "reason": candidate["untestable_reason"]}
            _write_report()
            continue

        asset, timeframe = candidate["asset"], candidate["timeframe"]
        key = (asset, timeframe)
        if key not in history_cache:
            print(f"[{idx}/{len(EXTERNAL_CANDIDATES)}] fetching full history for {asset}/{timeframe} ...", flush=True)
            history_cache[key] = fetch_full_history(asset, timeframe, client)
            print(f"  -> {len(history_cache[key])} candles", flush=True)
        candles = history_cache[key]

        hypothesis = {
            "hypothesis_name": name, "asset": asset, "timeframe": timeframe,
            "generated_at": now.isoformat(),
            "structured_entry_rule": candidate["structured_entry_rule"],
            "structured_exit_plan": candidate["structured_exit_plan"],
        }
        print(f"[{idx}/{len(EXTERNAL_CANDIDATES)}] {name}: running frequency_gate + harness ...", flush=True)
        run = run_hypothesis_live(hypothesis, candles, now, client=client, backtest_params=candidate["backtest_params"])
        result = run["result"]
        grid_note = f" grid_shift={len(run['grid_shift'])} offsets" if run["grid_shift"] else ""
        print(
            f"[{idx}/{len(EXTERNAL_CANDIDATES)}] {name} done: freq={result.frequency_classification} "
            f"verdict={result.verdict}{grid_note} -- {result.reason}",
            flush=True,
        )
        runs[name] = {"name": name, "asset": asset, "timeframe": timeframe, **_to_jsonable(run)}
        _write_report()
        print(f"  -> report updated at {report_path} ({len(runs)}/{len(EXTERNAL_CANDIDATES)} runs so far)", flush=True)

    report = _write_report()
    print(f"\n=== DONE. report written to {report_path} ===", flush=True)
    return report


if __name__ == "__main__":
    main()
