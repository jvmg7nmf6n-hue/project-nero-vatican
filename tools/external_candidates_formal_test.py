# Shared entry rule for all 3 WISE_MAN_HOLD-family candidates: long only,
# ADX14 < 25 AND close < BB lower AND ATR14 > 0 ("no open trade" is enforced
# structurally by auto_tester.run_backtest's own one-position-at-a-time
# convention, never an explicit condition -- matches the native WISE_MAN_HOLD
# family's own established pattern).
WISE_MAN_EXT_ENTRY_RULE = {
    "conditions": [
        {"field": "close", "op": "lt", "compare_to_field": "bb_lower"},
        {"field": "adx14", "op": "lt", "value": 25.0},
        {"field": "atr14", "op": "gt", "value": 0.0},
    ],
}

# Shared exit shape for all 3: percentage stop/target + a 2-consecutive-bar
# ADX regime-break, no time cap. Exit precedence (stop, then target, then
# regime-break, then time) is auto_tester._evaluate_exit_for_hypothesis's own
# existing, unchanged precedence -- matches the external spec exactly with
# zero engine changes needed (already proven: this combination parses and
# was smoke-tested directly before writing this file).
def _wise_man_ext_exit_plan(stop_pct: float, target_pct: float) -> dict:
    return {
        "stop_pct_of_entry": stop_pct,
        "target_pct_of_entry": target_pct,
        "regime_break_condition": {"field": "adx14", "op": "gte", "value": 28.0},
        "regime_break_consecutive_bars": 2,
    }


