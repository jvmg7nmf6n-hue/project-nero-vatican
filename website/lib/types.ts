// DEFAULT_BUDGET_LEDGER_PATH/EVE_SESSIONS_DIR), so fetchJson reaches them
// with no export step -- unlike eve_sessions/<id>.json (also under
// docs/site_data/, but one file PER session, not a single list), which this
// phase deliberately does not fetch: eve_session_registry.json's own
// classification/reason text already carries everything Phase 2's Session
// Health panel needs (see this branch's own closing report for the full
// plumbing finding). Deliberately minimal -- only the fields this site
// reads, not every real field these files carry.

export interface EveRawHypothesis {
  hypothesis_name?: string;
  mechanism?: string;
  asset?: string;
  timeframe?: string;
  // CC-1 directive, "every strategy page must show entry/exit rules and
  // trade frequency": the real DSL rule fields, already present on every
  // committed eve_hypotheses.json record, just not read by this site until
  // now -- see lib/ruleTranslation.ts.
  structured_entry_rule?: Record<string, unknown> | null;
  structured_exit_plan?: Record<string, unknown> | null;
  // CC-1 overnight directive, Part 1.3 (Learning Curve, Near-miss funnel):
  // real, already-validated declared-refinement field -- see B1's own work
  // (nero_core/eve/scoring.py::validate_derived_from).
  derived_from?: { parent_hypothesis_name?: string } | null;
}

export interface EveHypothesisRecord {
  session_id: string;
  raw_hypothesis: EveRawHypothesis;
  testability: string;
  verdict_combined: string | null;
  frequency_classification: string | null;
  measured_trades_per_year: number | null;
  contamination_tags: Array<{ tag: string }>;
  // CC-1 overnight directive, Part 1.3 (Learning Curve, Near-miss funnel):
  // real fields already on every committed record, just not read by this
  // site until now -- see nero_core/eve/context.py's own _is_near_miss logic
  // (reproduced client-side in lib/learningCurve.ts).
  verdict_is?: string | null;
  verdict_oos?: string | null;
  fdr_survives_is?: boolean | null;
  fdr_survives_oos?: boolean | null;
}

