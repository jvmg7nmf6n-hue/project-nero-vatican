// CC-1 overnight directive, Part 1.1 (Learning Curve): the real, auto-written
// per-session record under docs/site_data/eve_sessions/<id>.json. Deliberately
// minimal -- only the two fields the Reliability chart needs, matching this
// file's own "only the fields this site reads" discipline. `terminated_because`
// is always a real string on a written file ("end_session_called" on a clean
// completion, "crashed_mid_session" on a crash the crash-safety mechanism
// caught); `partial` is `true` only on a crash-caught record.
export interface EveSessionRecord {
  session_id: string;
  terminated_because: string;
  partial?: boolean;
}

export interface EveBudgetLedgerEntry {
  session_id: string;
  status: "reserved" | "actual" | "released";
  actual_cost_usd: number | null;
  projected_cost_usd: number;
  month: string;
  crash_reason?: string;
  crash_marked_at?: string;
}

// CC-1 directive Part B3a: one real, live-computed condition on a survivor
// strategy's own entry rule -- see nero_core/execution/export_survivor_distance.py's
// own docstring for why this is deliberately per-condition, never a combined score.
export interface SurvivorDistanceCondition {
  label: string;
  unit: "pct" | "rsi_points" | "z_units" | "boolean_state";
  distance: number | null;
  note?: string;
  raw_zscore?: number;
}

export interface SurvivorDistanceEntry {
  strategy_id: string;
  asset: string;
  timeframe: string;
  candle_close_time_ms: number;
  conditions: SurvivorDistanceCondition[];
  computed_at: string;
}

export interface SurvivorDistanceExport {
  schema_version: number;
  last_updated: string;
  distances: SurvivorDistanceEntry[];
  errors: { strategy: string; message: string }[];
}
